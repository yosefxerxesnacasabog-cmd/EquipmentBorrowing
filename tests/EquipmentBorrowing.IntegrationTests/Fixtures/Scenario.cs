using System.Text.Json;
using EquipmentBorrowing.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;
using Npgsql;

namespace EquipmentBorrowing.IntegrationTests.Fixtures;

public sealed class Scenario : IAsyncDisposable
{
    public const string AdminVariable = "LAB6_POSTGRES_ADMIN";
    private readonly string adminConnection;
    private bool created;
    private ApiFactory? factory;
    private HttpClient? client;
    public string DatabaseName { get; } = "lab6_" + Guid.NewGuid().ToString("N");
    public string ConnectionString { get; }
    public HttpClient Client => client ?? throw new InvalidOperationException("Scenario is not initialized.");

    private Scenario(string adminConnection)
    {
        this.adminConnection = adminConnection;
        ConnectionString = new NpgsqlConnectionStringBuilder(adminConnection)
        {
            Database = DatabaseName,
            Pooling = false,
            IncludeErrorDetail = false
        }.ConnectionString;
    }

    public static async Task<Scenario> CreateAsync()
    {
        var configured = Environment.GetEnvironmentVariable(AdminVariable);
        if (string.IsNullOrWhiteSpace(configured))
            throw new InvalidOperationException($"Set {AdminVariable} locally to a PostgreSQL connection with CREATEDB permission. Tests never silently pass or switch to an in-memory provider.");
        var scenario = new Scenario(configured);
        try
        {
            await scenario.AdminAsync($"CREATE DATABASE \"{scenario.DatabaseName}\"");
            scenario.created = true;
            await using (var db = scenario.NewContext())
                await db.Database.MigrateAsync();
            await scenario.ResetAsync();
            scenario.factory = new ApiFactory(scenario.ConnectionString);
            scenario.client = scenario.factory.CreateClient();
            return scenario;
        }
        catch
        {
            await scenario.DisposeAsync();
            throw;
        }
    }

    public EquipmentBorrowingDbContext NewContext() =>
        new FreshContextFactory(ConnectionString).CreateDbContext();

    public async Task<NpgsqlConnection> OpenFreshAsync()
    {
        var connection = new NpgsqlConnection(ConnectionString);
        await connection.OpenAsync();
        return connection;
    }

    public async Task ResetAsync()
    {
        await using var connection = await OpenFreshAsync();
        await using var transaction = await connection.BeginTransactionAsync();
        await using var command = new NpgsqlCommand(
            await File.ReadAllTextAsync(Path.Combine(AppContext.BaseDirectory, "Fixtures/reset.sql")), connection, transaction);
        command.Parameters.AddWithValue("d", FixedClock.D);
        await command.ExecuteNonQueryAsync();
        await transaction.CommitAsync();
    }

    public async Task<JsonElement> SnapshotAsync()
    {
        await using var connection = await OpenFreshAsync();
        await using var command = new NpgsqlCommand("""
            SELECT json_build_object(
              'students',(SELECT coalesce(json_agg(t ORDER BY t."Id"),'[]') FROM "Students" t),
              'equipment',(SELECT coalesce(json_agg(t ORDER BY t."Id"),'[]') FROM "Equipment" t),
              'borrowings',(SELECT coalesce(json_agg(t ORDER BY t."Id"),'[]') FROM "Borrowings" t))::text
            """, connection);
        return JsonDocument.Parse((string)(await command.ExecuteScalarAsync())!).RootElement.Clone();
    }

    private async Task AdminAsync(string sql)
    {
        await using var connection = new NpgsqlConnection(adminConnection);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync();
    }

    public async ValueTask DisposeAsync()
    {
        client?.Dispose();
        if (factory is not null) await factory.DisposeAsync();
        if (!created) return;
        // Identifier generated by this instance; never accept a caller-supplied DB
        // name for deletion, nor reuse the administrator's configured database.
        if (!System.Text.RegularExpressions.Regex.IsMatch(DatabaseName, "^lab6_[0-9a-f]{32}$"))
            throw new InvalidOperationException("Refusing to drop an unrecognized test database.");
        await AdminAsync($"DROP DATABASE \"{DatabaseName}\" WITH (FORCE)");
        created = false;
    }
}
